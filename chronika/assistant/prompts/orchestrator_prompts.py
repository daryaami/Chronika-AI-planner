from __future__ import annotations

from dataclasses import dataclass
from typing import Dict


@dataclass(frozen=True)
class PromptTemplate:
    key: str
    version: str
    content: str

    @property
    def qualified_version(self) -> str:
        return f"{self.key}@{self.version}"


