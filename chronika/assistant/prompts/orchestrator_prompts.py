        "=== ПРИОРИТЕТЫ ПРАВИЛ (сверху вниз) ===\n"
        "1. pending_context правила (confirm/cancel/modify)\n"
        "2. явные команды пользователя (delete/update/create)\n"
        "3. правила планирования (find_slots)\n"
        "4. оптимизации (избегай лишних вызовов)\n"
